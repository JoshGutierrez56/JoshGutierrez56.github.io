"""Targeted regression and screenshots for reviewer journey improvements."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / 'artifacts/iteration-4'
BASE = 'http://127.0.0.1:4173'
report = {'checks': [], 'errors': [], 'measurements': {}}

with sync_playwright() as pw:
    browser = pw.chromium.launch()
    page = browser.new_page(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
    page.on('pageerror', lambda error: report['errors'].append(str(error)))
    page.goto(BASE, wait_until='networkidle')
    expect(page.locator('.a-hero-copy a[href="mailto:gutierrewz.jos@northeastern.edu"]')).to_be_visible()
    expect(page.locator('.a-hero-copy a[href="https://www.linkedin.com/in/josh-gutierrez-mba-msf-55375a142/"]')).to_be_visible()
    page.locator('.a-explore-disclosure summary').click()
    expect(page.get_by_role('navigation', name='Explore the portfolio').get_by_role('link')).to_have_count(6)
    page.locator('.a-explore-disclosure summary').click()
    page.screenshot(path=str(OUT/'desktop.png'), full_page=True)
    page.screenshot(path=str(OUT/'desktop-first-screen.png'))
    report['checks'].append('Owner-approved contact links and expandable desktop navigation')
    page.get_by_role('tab', name='Interactive stories').click()
    expect(page.locator('#experience-panel-interactive')).to_be_visible()
    page.get_by_role('tab', name='Research overview').click()
    expect(page.locator('#experience-panel-interactive')).to_be_hidden()
    assert page.evaluate("Array.from(document.querySelectorAll('[aria-controls]')).every(e=>document.getElementById(e.getAttribute('aria-controls')))")
    report['checks'].append('Both homepage experience tabs have valid panel targets')
    page.set_viewport_size({'width':390, 'height':844})
    page.goto(BASE, wait_until='networkidle')
    expect(page.locator('#home-landscape')).to_be_hidden()
    report['measurements']['mobile_first_project_top'] = page.locator('.quick-review-cases>a').first.bounding_box()['y']
    page.screenshot(path=str(OUT/'mobile-first-screen.png'))
    page.screenshot(path=str(OUT/'mobile.png'), full_page=True)
    page.get_by_role('button', name='Explore the research landscape').click()
    expect(page.locator('#home-landscape')).to_be_visible()
    page.get_by_role('button', name='Close the research landscape').click()
    report['checks'].append('Mobile landscape preserved, expandable, and collapsed by default')
    page.set_viewport_size({'width':1440, 'height':1000})
    page.goto(BASE+'/research/', wait_until='networkidle')
    page.get_by_role('textbox', name='Search research').fill('housing')
    page.get_by_role('combobox', name='Order').select_option('name')
    expect(page.locator('.a-card')).to_have_count(1)
    filtered = page.url
    page.locator('.a-card a').first.click()
    page.go_back(wait_until='networkidle')
    expect(page.get_by_role('textbox', name='Search research')).to_have_value('housing')
    expect(page.get_by_role('combobox', name='Order')).to_have_value('name')
    expect(page.locator('.a-card')).to_have_count(1)
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('textbox', name='Search research')).to_have_value('housing')
    page.get_by_role('button', name='Reset filters', exact=True).click()
    expect(page.locator('.a-card')).to_have_count(17)
    assert '?' not in page.url
    page.get_by_role('textbox', name='Search research').fill('housing')
    page.get_by_role('navigation', name='Primary navigation').get_by_role('link', name='Research', exact=True).click()
    expect(page.get_by_role('textbox', name='Search research')).to_have_value('')
    expect(page.locator('.a-card')).to_have_count(17)
    report['checks'].append('Library query/sort survive project → Back and reload; reset clears URL')
    page.keyboard.press('Control+k')
    page.get_by_role('textbox', name='Search projects and pages').fill('housing')
    expect(page.locator('.a-search-results > a')).to_have_count(1)
    page.keyboard.press('Escape')
    expect(page.get_by_role('navigation', name='Primary navigation').get_by_role('link', name='Research', exact=True)).to_be_focused()
    page.get_by_role('button', name='Search site').click()
    page.keyboard.press('Escape')
    expect(page.get_by_role('button', name='Search site')).to_be_focused()
    report['checks'].append('Same-route navigation clears filters; keyboard search finds housing and restores focus')
    page.goto(BASE+'/research/customization/', wait_until='networkidle')
    page.get_by_role('button', name='Sources & limitations', exact=True).click()
    expect(page.get_by_role('tab', name='Sources & limits', exact=True)).to_have_attribute('aria-selected', 'true')
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('tab', name='Sources & limits', exact=True)).to_have_attribute('aria-selected', 'true')
    page.goto(BASE+'/research/customization/', wait_until='networkidle')
    page.screenshot(path=str(OUT/'case-study.png'), full_page=True)
    report['checks'].append('One-click source chapter opens and survives reload')
    page.goto(BASE+'/about/', wait_until='networkidle')
    expect(page.locator('#contact a[href^="mailto:"]')).to_be_visible()
    page.locator('#contact').screenshot(path=str(OUT/'contact.png'))
    report['checks'].append('About has visible direct contact destinations')
    report['accessibility'] = []
    for route in ['/', '/research/', '/about/', '/research/customization/', '/start-here/', '/research-notes/']:
        page.goto(BASE+route, wait_until='networkidle')
        page.add_script_tag(path=str(ROOT.parent/'artifacts/atlas/axe.min.js'))
        result = page.evaluate('async () => { const r = await axe.run(); return r.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})); }')
        report['accessibility'].append({'route':route,'violations':result})
    page.set_viewport_size({'width':390, 'height':844})
    page.goto(BASE, wait_until='networkidle')
    page.add_script_tag(path=str(ROOT.parent/'artifacts/atlas/axe.min.js'))
    result = page.evaluate('async () => (await axe.run()).violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))')
    report['accessibility'].append({'route':'/ (mobile)','violations':result})
    browser.close()
OUT.joinpath('journey-checks.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
print(json.dumps(report, indent=2))
assert not report['errors']
assert all(not r['violations'] for r in report['accessibility'])
